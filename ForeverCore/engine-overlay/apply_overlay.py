"""Lay the ForeverCore level overlay over a clean MythicSim checkout.

The overlay never ships line diffs. It copies its own files, generates the level table from
leveling-data.json, and applies a few anchored rewrites from overlay.json. A required anchor that
does not match exactly the stated number of times stops the run: upstream changed that spot and a
human has to look, instead of a patch half-applying.

    python apply_overlay.py <engine checkout> [--leveling ../leveling-data.json] [--report out.json]
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys

HERE = Path(__file__).resolve().parent
CORE = HERE.parent
CLASSES = {
    'warrior': 'Class_ClassWarrior', 'paladin': 'Class_ClassPaladin', 'hunter': 'Class_ClassHunter',
    'rogue': 'Class_ClassRogue', 'priest': 'Class_ClassPriest', 'shaman': 'Class_ClassShaman',
    'mage': 'Class_ClassMage', 'warlock': 'Class_ClassWarlock', 'druid': 'Class_ClassDruid',
}
FIELDS = [('Health', 'health'), ('Mana', 'mana'), ('Agility', 'agility'), ('Strength', 'strength'),
          ('Intellect', 'intellect'), ('Spirit', 'spirit'), ('Stamina', 'stamina'),
          ('CritPerAgility', 'critPerAgility'), ('CritPerIntellect', 'critPerIntellect')]
# Literal level numbers in class code that the overlay does not rewrite; reported, never changed.
AUDIT = re.compile(r'([Ll]evel\w*\s*(==|>=|<=|<|>)\s*6[0-3]\b|\bLevel:\s*6[0-3]\b)')


class OverlayError(Exception):
    pass


def manifest():
    return json.loads((HERE / 'overlay.json').read_text())


def overlay_digest():
    """Identity of the overlay itself, so a lock names exactly what was laid over upstream."""
    h = hashlib.sha256()
    for path in sorted(p for p in HERE.rglob('*') if p.is_file() and '__pycache__' not in p.parts):
        h.update(str(path.relative_to(HERE)).encode() + b'\0' + path.read_bytes() + b'\0')
    return h.hexdigest()[:16]


def level_table(leveling):
    data = json.loads(Path(leveling).read_text())
    lines = ['// Code generated by ForeverCore/engine-overlay/apply_overlay.py. DO NOT EDIT.',
             f'// Source: leveling-data.json, client {data.get("clientBuild")}, '
             f'{data.get("provenance", {}).get("clientTable", "?")}.', '', 'package core', '',
             'import "github.com/wowsims/forever/sim/core/proto"', '',
             'var foreverCoreBaseStatsByLevel = map[proto.Class]map[int32]foreverCoreLevelRow{']
    for name, enum in CLASSES.items():
        rows = data['classes'].get(name)
        if not rows:
            raise OverlayError(f'leveling data has no class {name}')
        missing = [lv for lv in range(10, 61) if str(lv) not in rows]
        if missing:
            raise OverlayError(f'leveling data {name} misses levels {missing}')
        lines.append(f'\tproto.{enum}: {{')
        for lv in range(10, 61):
            row = rows[str(lv)]
            parts = ', '.join(f'{go}: {float(row[key])!r}' for go, key in FIELDS)
            lines.append(f'\t\t{lv}: {{{parts}}},')
        lines.append('\t},')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def apply(engine, leveling):
    engine = Path(engine).resolve()
    spec = manifest()
    report = {'overlay': overlay_digest(), 'applied': [], 'skipped': [], 'files': []}
    # Check every anchor before touching a file, so a failure leaves the checkout untouched.
    planned = []
    for rw in spec['rewrites']:
        path = engine / rw['file']
        text = path.read_text() if path.exists() else ''
        found = len(re.findall(rw['pattern'], text))
        if found != rw['count']:
            entry = {'id': rw['id'], 'file': rw['file'], 'found': found, 'expected': rw['count']}
            if rw['required']:
                raise OverlayError(f"anchor {rw['id']} in {rw['file']}: found {found}, expected {rw['count']}")
            report['skipped'].append(entry)
            continue
        planned.append(rw)
    for rel in spec['files']:
        dest = engine / rel
        if dest.exists():
            raise OverlayError(f'{rel} already exists upstream; the overlay would overwrite it')
    for rel, src in spec['generated'].items():
        if (engine / rel).exists():
            raise OverlayError(f'{rel} already exists upstream')

    for rel in spec['files']:
        dest = engine / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(HERE / 'files' / rel, dest)
        report['files'].append(rel)
    for rel, src in spec['generated'].items():
        (engine / rel).write_text(level_table(leveling))
        report['files'].append(rel)
    for rw in planned:
        path = engine / rw['file']
        path.write_text(re.sub(rw['pattern'], rw['replace'], path.read_text()))
        report['applied'].append(rw['id'])

    audit = []
    for go in sorted((engine / 'sim').rglob('*.go')):
        if go.name.endswith('_test.go') or 'auto_gen' in go.name or go.name.startswith('zz_forevercore') or 'encounters' in go.parts:
            continue
        for n, line in enumerate(go.read_text().splitlines(), 1):
            if AUDIT.search(line):
                audit.append(f'{go.relative_to(engine)}:{n}: {line.strip()[:140]}')
    report['levelLiterals'] = audit
    return report


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('engine', type=Path)
    p.add_argument('--leveling', type=Path, default=CORE / 'leveling-data.json')
    p.add_argument('--report', type=Path)
    a = p.parse_args()
    try:
        report = apply(a.engine, a.leveling)
    except OverlayError as e:
        print(f'OVERLAY FAILED: {e}', file=sys.stderr)
        sys.exit(2)
    out = json.dumps(report, indent=1)
    if a.report:
        a.report.write_text(out + '\n')
    print(f"overlay {report['overlay']}: {len(report['applied'])} rewrites, {len(report['skipped'])} optional skipped, "
          f"{len(report['levelLiterals'])} level literals to review")


if __name__ == '__main__':
    main()
